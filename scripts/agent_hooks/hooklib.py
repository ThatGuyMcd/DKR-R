"""Shared plumbing for the AI coding agent hooks in this directory.

Claude Code (.claude/settings.json) and Codex (.codex/hooks.json) both run
these scripts through ``run`` with the hook payload as JSON on stdin. The two
agents use the same event names and the same exit status contract: 0 lets the
action proceed, 2 blocks it and feeds stderr back to the agent. Anything else
is a hook error that the agent reports but does not act on, so a broken hook
never wedges a session.

Edits arrive in two shapes. Claude sends ``tool_input.file_path`` with
``content`` (Write), ``old_string``/``new_string`` (Edit), ``edits`` (MultiEdit)
or ``notebook_path`` (NotebookEdit). Codex sends ``apply_patch`` with the patch
text in ``tool_input.command``. ``planned_edits`` turns either into the
would-be content of each file.

Standard library only.
"""

# pyright: strict

from __future__ import annotations

from collections.abc import Iterator, Mapping
import dataclasses
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
from typing import Any, cast

SCRIPTS = Path(__file__).resolve().parents[1]
if str(SCRIPTS) not in sys.path:
    sys.path.insert(0, str(SCRIPTS))

import pattern_guard  # noqa: E402  (needs the sys.path entry above)

# A checkout counts as DKR-R when it carries the guard; the hooks stay out of
# any other repository an agent happens to touch.
MARKER = "scripts/pattern_guard.py"
SESSION_BASE = ".claude/session-base"
SESSION_LIMIT = 32
# Every hook script `pre-commit install` writes carries this line.
PRE_COMMIT_MARK = "File generated by pre-commit"

Payload = Mapping[str, Any]


def read_payload() -> Payload:
    """The hook payload from stdin; an empty or malformed payload reads as {}."""
    try:
        payload = json.loads(sys.stdin.read() or "{}")
    except json.JSONDecodeError:
        return {}
    return cast(Payload, payload) if isinstance(payload, dict) else {}


def git(root: Path, *args: str) -> str | None:
    """Stripped stdout of a git command in root, or None if it failed."""
    try:
        result = subprocess.run(
            ["git", "-C", str(root), *args], stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, text=True
        )
    except OSError:
        return None
    return result.stdout.strip() if result.returncode == 0 else None


def checkout_of(path: Path) -> Path | None:
    """The DKR-R work tree containing path (which may not exist yet)."""
    directory = path if path.is_dir() else path.parent
    while not directory.is_dir() and directory != directory.parent:
        directory = directory.parent
    top = git(directory, "rev-parse", "--show-cdup")
    if top is None:
        return None
    root = (directory / top).resolve()
    return root if (root / MARKER).is_file() else None


def project_root(payload: Payload) -> Path | None:
    """The checkout the session works in: the payload's cwd (which follows the
    agent into a worktree), then $CLAUDE_PROJECT_DIR, then this script's own."""
    candidates = [payload.get("cwd"), os.environ.get("CLAUDE_PROJECT_DIR"), str(SCRIPTS.parent)]
    for candidate in candidates:
        if isinstance(candidate, str) and candidate:
            root = checkout_of(Path(candidate))
            if root is not None:
                return root
    return None


def relative(root: Path, path: Path) -> str | None:
    """path as a root-relative POSIX string, or None if it lies outside root."""
    resolved = path.parent.resolve() / path.name
    try:
        return resolved.relative_to(root).as_posix()
    except ValueError:
        return None


# --- Planned edits -------------------------------------------------------------


@dataclasses.dataclass(frozen=True)
class PlannedEdit:
    """One file an edit tool is about to write. ``text`` is the content after
    the edit, or None when the hook can't reconstruct it (the rules then see
    the current file)."""

    path: Path
    text: str | None


def _current(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return ""


def _replace(text: str, old: str, new: str, every: bool) -> str:
    """Apply one Edit. If old_string is missing the tool call will fail, but
    the new text is still judged, appended, so a violation can't slip past."""
    if old and old in text:
        return text.replace(old, new) if every else text.replace(old, new, 1)
    return f"{text}\n{new}"


def planned_edits(payload: Payload) -> list[PlannedEdit]:
    """Files the payload's edit tool call would write, with their new text."""
    tool = payload.get("tool_name")
    raw = payload.get("tool_input")
    tool_input: Mapping[str, Any] = cast(Mapping[str, Any], raw) if isinstance(raw, dict) else {}
    cwd = Path(str(payload.get("cwd") or os.getcwd()))

    def resolve(name: object) -> Path | None:
        return cwd / name if isinstance(name, str) and name else None

    if tool == "apply_patch" or (tool in ("Edit", "Write") and "command" in tool_input):
        command = tool_input.get("command")
        return list(_apply_patch(str(command), cwd)) if isinstance(command, str) else []
    if tool == "NotebookEdit":
        path = resolve(tool_input.get("notebook_path"))
        return [PlannedEdit(path, None)] if path else []
    path = resolve(tool_input.get("file_path"))
    if path is None:
        return []
    if tool == "Write":
        content = tool_input.get("content")
        return [PlannedEdit(path, content if isinstance(content, str) else None)]
    if tool == "Edit":
        text = _replace(
            _current(path),
            str(tool_input.get("old_string") or ""),
            str(tool_input.get("new_string") or ""),
            bool(tool_input.get("replace_all")),
        )
        return [PlannedEdit(path, text)]
    if tool == "MultiEdit":
        text = _current(path)
        edits = tool_input.get("edits")
        for edit in cast(list[Any], edits) if isinstance(edits, list) else []:
            if isinstance(edit, dict):
                fields = cast(Mapping[str, Any], edit)
                text = _replace(
                    text,
                    str(fields.get("old_string") or ""),
                    str(fields.get("new_string") or ""),
                    bool(fields.get("replace_all")),
                )
        return [PlannedEdit(path, text)]
    return [PlannedEdit(path, None)]


def _apply_patch(patch: str, cwd: Path) -> Iterator[PlannedEdit]:
    """Files touched by a Codex apply_patch envelope (``*** Begin Patch``).

    Add File yields the added lines. Update File applies each hunk by finding
    its context and removed lines in the current text; a hunk that doesn't
    match contributes its added lines at the end instead, which errs towards
    judging the new text. Deleted files yield nothing."""
    path: Path | None = None
    source: Path | None = None
    added: list[str] | None = None
    hunks: list[list[str]] = []

    def flush() -> Iterator[PlannedEdit]:
        if path is None:
            return
        if added is not None:
            yield PlannedEdit(path, "".join(f"{line}\n" for line in added))
        else:
            yield PlannedEdit(path, _apply_hunks(_current(source or path), hunks))

    for line in patch.splitlines():
        header = line.strip()
        for prefix in ("*** Add File: ", "*** Update File: ", "*** Delete File: "):
            if header.startswith(prefix):
                yield from flush()
                target = cwd / header[len(prefix) :].strip()
                path = source = None if prefix == "*** Delete File: " else target
                added = [] if prefix == "*** Add File: " else None
                hunks = []
                break
        else:
            if header.startswith("*** Move to: ") and path is not None:
                path = cwd / header[len("*** Move to: ") :].strip()
            elif header.startswith("***"):
                continue
            elif added is not None:
                added.append(line[1:] if line.startswith("+") else line)
            elif path is not None:
                if line.startswith("@@"):
                    hunks.append([])
                elif line[:1] in (" ", "+", "-") or line == "":
                    if not hunks:
                        hunks.append([])
                    hunks[-1].append(line or " ")
    yield from flush()


def _apply_hunks(text: str, hunks: list[list[str]]) -> str:
    lines = text.splitlines()
    cursor = 0
    tail: list[str] = []
    for hunk in hunks:
        before = [line[1:] for line in hunk if line[0] in " -"]
        after = [line[1:] for line in hunk if line[0] in " +"]
        for start in range(cursor, len(lines) - len(before) + 1):
            if lines[start : start + len(before)] == before:
                lines[start : start + len(before)] = after
                cursor = start + len(after)
                break
        else:
            tail.extend(line[1:] for line in hunk if line[0] == "+")
    return "".join(f"{line}\n" for line in lines + tail)


# --- Session base --------------------------------------------------------------


def load_sessions(root: Path) -> dict[str, dict[str, Any]]:
    """session id -> what session_start.py recorded for it."""
    try:
        data = json.loads((root / SESSION_BASE).read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return {}
    sessions = cast(dict[str, Any], data).get("sessions") if isinstance(data, dict) else None
    if not isinstance(sessions, dict):
        return {}
    return {
        str(key): cast(dict[str, Any], value)
        for key, value in cast(dict[Any, Any], sessions).items()
        if isinstance(value, dict)
    }


def save_sessions(root: Path, sessions: Mapping[str, Mapping[str, Any]]) -> None:
    """Keep the newest SESSION_LIMIT entries (dicts keep insertion order)."""
    kept = dict(list(sessions.items())[-SESSION_LIMIT:])
    target = root / SESSION_BASE
    target.parent.mkdir(parents=True, exist_ok=True)
    scratch = target.with_name(f"{target.name}.{os.getpid()}.tmp")
    scratch.write_text(json.dumps({"sessions": kept}, indent=1, sort_keys=True) + "\n", encoding="utf-8")
    os.replace(scratch, target)


# --- Guard problems ------------------------------------------------------------


def changed_paths(root: Path, base: str) -> set[str]:
    """Tracked paths that differ from base (commits and local edits), plus
    untracked, non-ignored files."""
    changed: set[str] = set()
    for args in (
        ("diff", "--name-only", "--no-renames", "-z", base),
        ("ls-files", "--others", "--exclude-standard", "-z"),
    ):
        changed |= {path for path in (git(root, *args) or "").split("\0") if path}
    return changed


def guard_problems(root: Path, paths: set[str], base: str | None) -> dict[str, str]:
    """Pattern guard problems for the given paths, keyed so that two runs can
    be compared: a finding the baseline doesn't list, a baseline entry for one
    of the paths that no longer fires, and a baseline entry added since base.
    Values are the rendered messages."""
    tree = pattern_guard.Tree(root)
    scanned = sorted(path for path in paths if tree.is_scanned(path))
    findings = pattern_guard.scan(tree, scanned)
    baseline_path = root / pattern_guard.BASELINE
    try:
        baseline = pattern_guard.parse_baseline(baseline_path.read_text(encoding="utf-8"), str(pattern_guard.BASELINE))
    except FileNotFoundError:
        baseline = {}
    problems: dict[str, str] = {}
    for finding in findings:
        if (finding.path, finding.rule) not in baseline:
            problems.setdefault(f"new {finding.path} {finding.rule}", finding.render())
    found = {(finding.path, finding.rule) for finding in findings}
    for (path, rule), number in baseline.items():
        if path in paths and (path, rule) not in found:
            problems[f"stale {path} {rule}"] = (
                f"{pattern_guard.BASELINE}:{number}: {rule} stale entry, {path} no longer matches\n"
                "    instead: delete the line (the baseline only shrinks)"
            )
    before = pattern_guard.committed_baseline(tree, base) if base else None
    grown = [entry for entry in baseline.items() if before is not None and entry[0] not in before]
    for (path, rule), number in grown:
        problems[f"grown {path} {rule}"] = (
            f"{pattern_guard.BASELINE}:{number}: {rule} new baseline entry for {path}\n"
            "    instead: fix the finding; the baseline only shrinks"
        )
    return problems


def hooks_status(root: Path) -> str | None:
    """None when the pre-commit git hook is installed, otherwise how to fix it."""
    if not (root / ".pre-commit-config.yaml").is_file():
        return None
    bootstrap = (
        "python3 scripts/bootstrap_hooks.py"
        if (root / "scripts/bootstrap_hooks.py").is_file()
        else "pre-commit install"
    )
    if shutil.which("pre-commit") is None:
        return f"pre-commit is not installed, so local git hooks don't run. Bootstrap with `{bootstrap}`."
    hook = git(root, "rev-parse", "--path-format=relative", "--git-path", "hooks/pre-commit")
    try:
        installed = hook is not None and PRE_COMMIT_MARK in (root / hook).read_text(encoding="utf-8", errors="replace")
    except OSError:
        installed = False
    return None if installed else f"The pre-commit git hook is not installed. Bootstrap with `{bootstrap}`."


def registries_failure(root: Path) -> str | None:
    """scripts/check_registries.py output if it exists and fails, else None."""
    script = root / "scripts/check_registries.py"
    if not script.is_file():
        return None
    result = subprocess.run(
        [sys.executable, str(script)], cwd=root, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True
    )
    if result.returncode == 0:
        return None
    return result.stdout.strip() or "scripts/check_registries.py failed"
