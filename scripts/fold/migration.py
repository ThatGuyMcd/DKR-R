#!/usr/bin/env python3
"""Write docs/fold-in/MIGRATION.md: where each v1.0.11 layer's code lives now.

    migration.py --reference DIR

For every release layer and capsule role that contributed first-party files
to the shipped v1.0.11 binaries (the reference's final-sources.json), the
folded directories those files went to, with counts, from the same mapping
apply_closure.py wrote the files with. Layers that held no compiled source
(dependency patch sets, services, release tooling) are listed from
OTHER_LAYERS. Fold-only, like the rest of scripts/fold/.
"""

from __future__ import annotations

import argparse
from collections import Counter, defaultdict
import json
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
import apply_closure  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "docs/fold-in/MIGRATION.md"
# Up to this many files, a layer's row names them; past it, their directories.
LISTED = 12
# Layers under patches/ before B8 that compiled no first-party file into the
# shipped binaries, and where their content went.
OTHER_LAYERS = {
    "android, hlslpp, libdatachannel, libjuice, n64-modern-runtime, n64recomp, nfd, performance, "
    "plume, rt64, sdl2, sljit, startup-memory, usrsctp, custom-magic-codes, netplay": (
        "registered dependency patches, still in `patches/<dependency>/` (`patches/manifest.json`); "
        "their layer notes and scripts are gone"
    ),
    "enhanced-water": "RT64 shaders and render sources in `runtime-recomp/src/water/`; its patches stay in "
    "`patches/enhanced-water/`",
    "online-directory (backend)": "`services/online-directory/`",
    "mod-store (backend)": "`services/mod-store/`",
    "library-workflow": "`services/library-workflow/`",
    "save-layout, character-portraits": "guest inputs in `runtime-recomp/guest/`; the stages are "
    "`scripts/save_layout_pipeline.py` and `scripts/character_portrait_pipeline.py` (run by "
    "`scripts/prepare_payloads.py`)",
    "camera-plus (scene kernel)": "`scripts/camera_scene_kernel.py` (run by `scripts/prepare_payloads.py`)",
    "release-prep": "`scripts/release/` and `docs/releases/<version>/`",
    "camera-shadow": "`runtime-recomp/src/game/camera_shadow_kernel.c` (first-party since B4)",
    "vanilla-water, credits-viewport, title-text, viewport-flow, presentation-polish, launcher-polish, "
    "character-library-portraits, performance-surgical, camera-plus (native)": "composed into the capsule roles "
    "above (most into sdk2-base) before v1.0.11 was frozen; their files are in those rows",
}


def rows(reference: Path) -> dict[Path, str]:
    """Reference staged path -> the layer or capsule role it came from."""
    data = json.loads((reference / "final-sources.json").read_text(encoding="utf-8"))
    return {
        ROOT / entry["final_staged_path"]: entry["stage"] for entry in data["files"] if entry["kind"] == "first-party"
    }


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--reference", type=Path, required=True)
    a = p.parse_args(argv)
    reference = apply_closure.load_reference(a.reference, ROOT)
    destinations = apply_closure.plan(reference, ROOT).destinations
    by_layer: dict[str, Counter[str]] = defaultdict(Counter)
    files: dict[str, set[str]] = defaultdict(set)
    for staged, stage in rows(a.reference).items():
        dest = destinations.get(staged)
        if dest is None:
            continue
        name = stage.split(":", 1)[1] if ":" in stage else stage
        name = name.lower().replace("_", "-") if stage.startswith("capsule:") else name
        by_layer[name][str(Path(dest).parent)] += 1
        files[name].add(dest)
    lines = [
        "# What moved where",
        "",
        "Through v1.0.11 the release was a base tree plus a chain of first-party",
        "layers under `patches/` (and a frozen source capsule). The fold wrote the",
        "shipped code into the tree. For each layer, or capsule role, that",
        "contributed first-party source to the v1.0.11 binaries, where that code",
        "is now: the files, or for the big ones their directories with file",
        'counts. Fix a bug in "layer X" by editing those files; there is no layer',
        "to regenerate.",
        "",
        "Generated by `scripts/fold/migration.py --reference <v1.0.11 reference>`.",
        "",
        "| Layer or capsule role | Folded into (files) |",
        "|---|---|",
    ]
    for layer in sorted(by_layer):
        if len(files[layer]) <= LISTED:
            places = ", ".join(f"`{f}`" for f in sorted(files[layer]))
        else:
            ranked = sorted(by_layer[layer].items(), key=lambda kv: (-kv[1], kv[0]))
            places = ", ".join(f"`{d}/` ({n})" for d, n in ranked)
        lines.append(f"| {layer} | {places} |")
    lines += ["", "## Layers with no compiled source", "", "| Layer | Now |", "|---|---|"]
    lines += [f"| {layer} | {place} |" for layer, place in OTHER_LAYERS.items()]
    lines += [
        "",
        "Removed and renamed scripts, with their replacements, are listed in",
        "[open-items.md](open-items.md#removed-or-renamed-entrypoints).",
        "",
    ]
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"migration: {len(by_layer)} layers and roles written to {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
